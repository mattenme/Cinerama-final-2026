CREATE TABLE COMPRA (
    ID_COMPRA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CLIENTE         NUMBER NOT NULL,
    ID_FUNCION         NUMBER NOT NULL,
    PRECIO             NUMBER(10,2) NOT NULL,
    METODO_PAGO        VARCHAR2(50 CHAR),
    ESTADO             VARCHAR2(50 CHAR) DEFAULT 'PENDIENTE',
    CODIGO_QR          VARCHAR2(500 CHAR),
    FECHA_COMPRA       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRODUCTOS          VARCHAR2(2000 CHAR),
    ASIENTOS           VARCHAR2(500 CHAR),
    TOTAL_PRODUCTOS    NUMBER(10,2),
    USADO              NUMBER(1,0) DEFAULT 0,
    FECHA_USO          TIMESTAMP(6),
    FECHA_CANCELACION  TIMESTAMP(6),
    CONSTRAINT PK_COMPRA PRIMARY KEY (ID_COMPRA),
    CONSTRAINT FK_COMPRA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_COMPRA_FUNCION FOREIGN KEY (ID_FUNCION) REFERENCES FUNCION (ID_FUNCION)
)
SEGMENT CREATION IMMEDIATE
PCTFREE 10
STORAGE (INITIAL 64K NEXT 256K MINEXTENTS 1 MAXEXTENTS UNLIMITED PCTINCREASE 0)
TABLESPACE USERS;

CREATE TABLE COMPRA_DETALLE (
    ID_DETALLE  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_COMPRA   NUMBER NOT NULL,
    ID_FUNCION  NUMBER NOT NULL,
    ID_ASIENTO  NUMBER NOT NULL,
    PRECIO      NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_COMPRA_DETALLE PRIMARY KEY (ID_DETALLE),
    CONSTRAINT UK_COMPRA_DETALLE_FUNCION_ASIENTO UNIQUE (ID_FUNCION, ID_ASIENTO),
    CONSTRAINT FK_COMPRA_DETALLE_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA),
    CONSTRAINT FK_COMPRA_DETALLE_FUNCION FOREIGN KEY (ID_FUNCION) REFERENCES FUNCION (ID_FUNCION),
    CONSTRAINT FK_COMPRA_DETALLE_ASIENTO FOREIGN KEY (ID_ASIENTO) REFERENCES ASIENTO (ID_ASIENTO)
)
SEGMENT CREATION IMMEDIATE
PCTFREE 10
STORAGE (INITIAL 64K NEXT 256K MINEXTENTS 1 MAXEXTENTS UNLIMITED PCTINCREASE 0)
TABLESPACE USERS;

CREATE TABLE VALIDACION (
    ID_VALIDACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_COMPRA     NUMBER,
    CODIGO_QR     VARCHAR2(500 CHAR) NOT NULL,
    ID_EMPLEADO   NUMBER,
    FECHA         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    RESULTADO     VARCHAR2(30 CHAR) NOT NULL,
    MENSAJE       VARCHAR2(300 CHAR),
    CONSTRAINT PK_VALIDACION PRIMARY KEY (ID_VALIDACION),
    CONSTRAINT FK_VALIDACION_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA)
)
SEGMENT CREATION IMMEDIATE
PCTFREE 10
STORAGE (INITIAL 64K NEXT 64K MINEXTENTS 1 MAXEXTENTS UNLIMITED PCTINCREASE 0)
TABLESPACE USERS;

CREATE INDEX IX_COMPRA_CODIGO_QR ON COMPRA (CODIGO_QR);
CREATE INDEX IX_VALIDACION_FECHA ON VALIDACION (FECHA);
CREATE INDEX IX_VALIDACION_COMPRA ON VALIDACION (ID_COMPRA);

COMMIT;

SELECT table_name, initial_extent, next_extent, pct_increase
  FROM user_tables
 WHERE table_name IN (
     'PELICULA','SALA','PRODUCTO','PROMOCION','ASIENTO','CLIENTE','FUNCION',
     'INCIDENCIA','CALIFICACION','COMPRA','COMPRA_DETALLE','VALIDACION')
 ORDER BY table_name;
