CREATE TABLE PELICULA (
    ID_PELICULA       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO            VARCHAR2(200 CHAR) NOT NULL,
    DURACION_MINUTOS  NUMBER NOT NULL,
    GENERO            VARCHAR2(100 CHAR),
    SINOPSIS          VARCHAR2(2000 CHAR),
    IMAGEN_URL        VARCHAR2(500 CHAR),
    DESTACADO         NUMBER(1,0) DEFAULT 0,
    ACTIVO            NUMBER(1,0) DEFAULT 1,
    CONSTRAINT PK_PELICULA PRIMARY KEY (ID_PELICULA)
)
SEGMENT CREATION IMMEDIATE
PCTFREE 10
STORAGE (INITIAL 64K NEXT 64K MINEXTENTS 1 MAXEXTENTS UNLIMITED PCTINCREASE 0)
TABLESPACE USERS;

