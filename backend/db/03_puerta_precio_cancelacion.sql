-- =====================================================================
-- Cinerama - Alta: puerta, precio de función y cancelación de compras
--
-- Ejecutar una vez con:
--   sqlplus cineramaBD/123@localhost:1521/XE @db/03_puerta_precio_cancelacion.sql
--
-- Es idempotente: cada columna/índice se crea solo si no existe. Hibernate
-- (ddl-auto: update) también crearía las columnas, pero este script deja el
-- esquema explícito y asigna el precio a las funciones antiguas.
-- =====================================================================

DECLARE
    PROCEDURE agregar_columna(p_tabla VARCHAR2, p_columna VARCHAR2, p_ddl VARCHAR2) IS
        v_existe NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_existe
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_tabla)
           AND COLUMN_NAME = UPPER(p_columna);
        IF v_existe = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_tabla || ' ADD (' || p_ddl || ')';
        END IF;
    END;

    PROCEDURE crear_indice(p_nombre VARCHAR2, p_ddl VARCHAR2) IS
        v_existe NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_existe
          FROM USER_INDEXES
         WHERE INDEX_NAME = UPPER(p_nombre);
        IF v_existe = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    -- Precio por butaca definido en la función (antes estaba fijo en el código).
    agregar_columna('FUNCION', 'PRECIO', 'PRECIO NUMBER(10,2)');

    -- Estado de uso de la entrada y bitácora de la puerta.
    agregar_columna('COMPRA', 'USADO', 'USADO NUMBER(1) DEFAULT 0 NOT NULL');
    agregar_columna('COMPRA', 'FECHA_USO', 'FECHA_USO TIMESTAMP');
    agregar_columna('COMPRA', 'ASIENTOS', 'ASIENTOS VARCHAR2(500)');

    -- Cancelación de compras (la compra ya no se borra).
    agregar_columna('COMPRA', 'FECHA_CANCELACION', 'FECHA_CANCELACION TIMESTAMP');

    -- La puerta busca por código QR en cada lectura.
    crear_indice('IX_COMPRA_CODIGO_QR', 'CREATE INDEX IX_COMPRA_CODIGO_QR ON COMPRA (CODIGO_QR)');
END;
/

-- Funciones antiguas: la regla histórica era 25 para más de 120 minutos y 20 para el resto.
UPDATE FUNCION f
   SET f.PRECIO = CASE
         WHEN (SELECT p.DURACION_MINUTOS FROM PELICULA p WHERE p.ID_PELICULA = f.ID_PELICULA) > 120
           THEN 25.00
         ELSE 20.00
       END
 WHERE f.PRECIO IS NULL;

COMMIT;

-- Tabla de validaciones de la puerta.
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE VALIDACION (
            ID_VALIDACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ID_COMPRA     NUMBER,
            CODIGO_QR     VARCHAR2(500) NOT NULL,
            ID_EMPLEADO   NUMBER,
            FECHA         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            RESULTADO     VARCHAR2(30) NOT NULL,
            MENSAJE       VARCHAR2(300),
            CONSTRAINT FK_VALIDACION_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRA (ID_COMPRA)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN -- ORA-00955: la tabla ya existe
            RAISE;
        END IF;
END;
/

DECLARE
    PROCEDURE crear_indice(p_nombre VARCHAR2, p_ddl VARCHAR2) IS
        v_existe NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_existe
          FROM USER_INDEXES
         WHERE INDEX_NAME = UPPER(p_nombre);
        IF v_existe = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    crear_indice('IX_VALIDACION_FECHA', 'CREATE INDEX IX_VALIDACION_FECHA ON VALIDACION (FECHA)');
    crear_indice('IX_VALIDACION_COMPRA', 'CREATE INDEX IX_VALIDACION_COMPRA ON VALIDACION (ID_COMPRA)');
END;
/

COMMIT;

SELECT COLUMN_NAME, DATA_TYPE, NULLABLE
  FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME IN ('COMPRA', 'FUNCION', 'VALIDACION')
   AND COLUMN_NAME IN ('PRECIO', 'USADO', 'FECHA_USO', 'ASIENTOS', 'FECHA_CANCELACION',
                       'RESULTADO', 'CODIGO_QR')
 ORDER BY TABLE_NAME, COLUMN_NAME;
